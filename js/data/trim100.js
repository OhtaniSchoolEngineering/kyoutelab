/* 問題数を A・B・C それぞれ 100 問にそろえる（2026-11-19）
   学習効果の薄いものを外す。基準:
   A … ほかの A と同じ知識を問う重複、一問一答のカードとまったく同じ内容
   B … 数値まで同じ題材の重複
   C … すでにある B・C と題材が重なる大問、
       リード文や表を読むだけで答えが出る（読解になっていない）単問
   問題そのものは元のファイルに残してあり、ここで外しているだけ。もどすときはリストから消す */
window.CHEM = window.CHEM || {};
(function () {
  'use strict';
  var C = window.CHEM;
  var DROP_Q = [
    /* A（16） */
    'qa03' /* 触媒と反応エンタルピー（kin01・thm01 と同じ） */, 'thm06' /* 光と反応（tf-thm と同じ） */,
    'qa16' /* 分子結晶はどれ（tf-str・str01 に含まれる） */, 'gas05' /* 理想気体に近づく条件（qa08 と同じ） */,
    'sol01' /* コロイド（tf-col と同じ） */, 'qa13' /* 酸化数が最も大きい（rdx01 と同じ） */,
    'qa15' /* 実用電池（ele01・tf-ele と同じ） */, 'qa05' /* 共通イオン効果（ksp03 と同じ） */,
    'ion01' /* 希塩酸で沈殿（tf-ion に含まれる・カードと同じ） */, 'tf-mt' /* Al と濃硝酸（nm06 と同じ） */,
    'al07' /* アセチレン + 水（カードと同じ） */, 'na01' /* 還元性のない二糖（tf-nat と同じ） */,
    'po10' /* アクリル繊維（カードと同じ） */, 'qa02' /* 原子量の基準（mol-a1・カードと同じ） */,
    'ar06' /* クメン法（カードと同じ。P23 の図にある） */, 'nm02' /* 上方置換（カードと同じ） */,
    /* B（10） */
    'qb21' /* 鉛蓄電池の負極（ele05 と同じ） */, 'qb24' /* H_2 + I_2 の平衡（eq03 と同じ） */,
    'qb25' /* N_2O_4 の解離（eq07 と同じ） */, 'qb19' /* 銅と希硝酸（nm-b1 と同じ） */,
    'qb23' /* NaOH の溶解熱（thm05 と同じ） */, 'qb11' /* 油脂のけん化（al04 と同じ） */,
    'qb12' /* ナイロン 66 のアミド結合（po05 と同じ） */, 'qb14' /* アルコール発酵（na05 と同じ） */,
    'qb26' /* AgCl の溶解度（ksp02 と同じ） */, 'dt04' /* Mg と塩酸のグラフ（総合の大問 sg03 と同じ） */,
    /* C の単問（4） */
    'gas08' /* 表の Z を読むだけ */, 'xc10' /* 表から温度を読むだけ */,
    'cbq1' /* 答えがリード文に書いてある */, 'po09' /* B の計算（重合度）で、読解になっていない */
  ];
  var DROP_SET = [ /* C の大問（4 題 × 3 問）。すでにある B・C の問題と題材が重なるもの */
    'cs11' /* 油脂のヨウ素価（B の al05 と同じ計算） */, 'mx03' /* 加熱による質量の変化（cb05 と同じ題材） */,
    'cb03' /* イオン交換膜法（B の qb20 と同じ装置・計算） */, 'cs10' /* NaOH と Na_2CO_3 の混合物（B の ab08・tc06 と同じ滴定） */
  ];
  /* 2026-11-19: 一度外した X 線回折（cm05）・DNA（cm19）・立体異性体（mx11）・電池のエネルギー（mx13）は先生の判断でもどした */
  C.questions = C.questions.filter(function (q) { return DROP_Q.indexOf(q.id) < 0 && DROP_SET.indexOf(q.set) < 0; });
  C.csets = (C.csets || []).filter(function (s) { return DROP_SET.indexOf(s.id) < 0; });
  C.trimmed = { q: DROP_Q, sets: DROP_SET };
})();
