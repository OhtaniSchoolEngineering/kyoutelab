/* 記述バンクから4択の正誤問題をつくる */
(function () {
  'use strict';
  var C = window.CHEM, pick = C.pick, shuffle = C.shuffle;
  function head(t) { return t.replace(/\s/g, '').slice(0, 6); }
  /* 書き出しが同じ記述や、正反対の組（X）は同じ問題に入れない */
  function clash(bk, a, b) {
    if (head(a) === head(b)) return true;
    return (bk.X || []).some(function (p) { return (a.indexOf(p[0]) >= 0 && b.indexOf(p[1]) >= 0) || (a.indexOf(p[1]) >= 0 && b.indexOf(p[0]) >= 0); });
  }
  function gen(bk) {
    var wrong = Math.random() < 0.7;
    var T = shuffle(bk.T.slice()), F = shuffle(bk.F.slice());
    var first = wrong ? { s: F[0], ok: false } : { s: T[0], ok: true }, rest = wrong ? T : F;
    /* 同じことを正反対に言う記述が並ぶと、見比べるだけで答えが分かってしまうので避ける */
    var items = [first];
    rest.forEach(function (x) { if (items.length < 4 && items.every(function (y) { return !clash(bk, x[0], y.s[0]); })) items.push({ s: x, ok: !first.ok }); });
    rest.forEach(function (x) { if (items.length < 4 && items.every(function (y) { return y.s !== x; })) items.push({ s: x, ok: !first.ok }); });
    var target = items[0];
    items = shuffle(items);
    var a = items.indexOf(target);
    var subj = pick(bk.subj);
    var q = pick([subj + 'に関する記述として' + (wrong ? '誤りを含むもの' : '正しいもの') + 'はどれか。',
      '次の ①〜④ は' + subj + 'に関する記述である。' + (wrong ? '誤りを含むもの' : '正しいもの') + 'を一つ選べ。']);
    var CIRC = ['①', '②', '③', '④'];
    return {
      q: q, c: items.map(function (x) { return x.s[0]; }), a: a,
      ce: items.map(function (x) { return { ok: x.ok, t: (x.ok ? '正しい。' : '誤り。') + x.s[1] }; }),
      e: (wrong ? '誤りを含むのは ' : '正しいのは ') + CIRC[a] + '。' + target.s[1],
      k: '正誤問題は1つずつ「正」「誤」を判定し、誤りならどこが違うかを言えるようにする。' + (wrong ? '「誤りを含むもの」を選ぶときは、正しいと確信できるものを先に消す。' : '「正しいもの」を選ぶときは、誤りの理由が言えるものを消していく。')
    };
  }
  C.stBank.forEach(function (bk) {
    var fm = { id: bk.id, u: bk.u, t: 'A', lv: bk.lv, p: ['P27'], name: bk.subj[0] + '（正誤）', gen: function () { return gen(bk); } };
    C.families = (C.families || []).concat([fm]);
    var q = { id: fm.id, u: fm.u, t: 'A', lv: fm.lv, p: fm.p, fam: fm };
    Object.assign(q, fm.gen());
    C.questions.push(q);
  });
})();
